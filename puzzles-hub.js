  function worldOf(i) { return i < 2 ? 0 : i < 4 ? 1 : i < 6 ? 2 : i < 8 ? 3 : 4; }

  const LEGS = 8;

  /* هندسة كل عالم تُحسب مرّة عند التحميل: أطوال الأرجل غير متساوية
     (الصعود أقصر من المشي الأفقي)، فنسبة الدرب المقطوع تُحسب بالطول
     الحقيقي لا بعدد المحطّات — وإلّا سبق الخطُّ القطعةَ أو تخلّف. */
  WORLDS.forEach(function (w) {
    const a = []; let tot = 0;
    for (let i = 0; i < LEGS; i++) {
      const d = Math.hypot(w.st[i + 1][0] - w.st[i][0], w.st[i + 1][1] - w.st[i][1]);
      a.push(d); tot += d;
    }
    w.seg = { a: a, tot: tot };
    w.d = 'M ' + w.st.map(function (p) { return p[0] + ' ' + p[1]; }).join(' L ');
  });

