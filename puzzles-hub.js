  function legOf(f) {
    const v = Math.max(0, Math.min(LEGS, f));
    let s = Math.floor(v);
    if (s >= LEGS) s = LEGS - 1;
    return { s: s, k: v - s };
  }
  function trailFrac(f) {
    const g = legOf(f);
    let d = 0;
    for (let i = 0; i < g.s; i++) d += P.seg.a[i];
    return (d + P.seg.a[g.s] * g.k) / P.seg.tot;
  }
  function heroAt(f) {
    const g = legOf(f), a = P.st[g.s], b = P.st[g.s + 1];
    return { x: a[0] + (b[0] - a[0]) * g.k, y: a[1] + (b[1] - a[1]) * g.k };
  }

